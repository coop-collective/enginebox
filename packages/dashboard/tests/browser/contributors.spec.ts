test('uses controller registration and allowances for both runtimes with the same details flow', async ({page, request}) => {
  await request.post(`${fixtureOrigin}/__test/reset`);
  await request.post(`${fixtureOrigin}/__test/contributor-inventory`);
  await request.post(`${fixtureOrigin}/__test/mode`, {data:{mode:'warm'}});
  await openMachines(page);
  const machines = page.getByRole('region', {name:'Registered machines',exact:true});
  const server = machines.getByRole('listitem',{name:'Machine Build machine',exact:true});
  const windows = machines.getByRole('listitem',{name:'Machine Render RTX',exact:true});
  await expect(server).toContainText('Registered · Linux · Incus');
  await expect(windows).toContainText('Registered · Windows · WSL2');
  await expect(server).toContainText('Online');
  await expect(server).toContainText('Capacity limited');
  // The controller allowance is lower than total hardware and must win.
  await expect(server).toContainText('28 CPU · 112 GiB memory');
  await expect(server).toContainText('900 GiB disk allowance');
  for (const row of [server, windows]) {
    await row.locator('summary').filter({hasText:'Details'}).click();
    await expect(row).toContainText('Runtime connected');
    await expect(row).toContainText('Available templates:');
    await expect(row).toContainText('Machine ID:');
  }
  await expect(server).toContainText('host:metal-01');
  await expect(windows).toContainText(`worker:${'1'.repeat(32)}`);
  await expect(server).toContainText('Available for new work: 16 CPU · 64 GiB memory · 0 GiB disk');
  await expect(server.getByRole('button',{name:'Revoke machine'})).toHaveCount(0);
  await expect(windows.getByRole('button',{name:'Revoke machine'})).toBeVisible();
  await page.setViewportSize({width:390,height:844});
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth)).toBe(true);
  await page.screenshot({path:'test-results/compute-consistent-mobile.png',fullPage:true});
});


test('Linux uses the shared installer flow, renews the matching code and stays one machine after enrollment or revoke',async({page,request})=>{
  await request.post(`${fixtureOrigin}/__test/reset`);
  await request.post(`${fixtureOrigin}/__test/managed-host`);
  await openMachines(page);
  const machines=page.getByRole('region',{name:'Registered machines',exact:true});
  const server=machines.getByRole('listitem',{name:'Machine Build machine',exact:true});
  await expect(machines.getByRole('listitem')).toHaveCount(2);
  await expect(server).toContainText('Registration required');
  await expect(page.getByRole('button',{name:'New workspace',exact:true})).toBeDisabled();
  await page.getByRole('button',{name:'Add machine',exact:true}).click();
  await page.getByRole('combobox',{name:'Operating system',exact:true}).selectOption('linux');
  await expect(page.getByLabel('Machine name',{exact:true})).toHaveCount(0);
  await expect(page.getByRole('combobox',{name:'Linux server',exact:true})).toHaveValue('metal-01');
  await expect(page.getByRole('combobox',{name:'Linux server',exact:true}).locator('option')).toHaveCount(2);
  await page.getByRole('button',{name:'Create install command',exact:true}).click();
  const command=page.getByLabel('Bash install command',{exact:true});
  await expect(command).toHaveValue(/install-linux-node\.sh/);
  await expect(command).toHaveValue(/sha256sum --check --status/);
  await expect(command).not.toHaveValue(/powershell/);
  await expect(machines.getByRole('listitem')).toHaveCount(2);
  await page.locator('summary').filter({hasText:'Pending registrations'}).click();
  await page.getByRole('list',{name:'Pending registrations'}).getByRole('button',{name:'Renew registration code'}).click();
  await expect(command).toHaveValue(new RegExp('c'.repeat(64)));
  await expect(page.getByLabel('Registration code',{exact:true})).toHaveValue(`${'4'.repeat(32)}.${'c'.repeat(64)}`);
  await request.post(`${fixtureOrigin}/__test/incus-online`);
  await page.getByRole('button',{name:'Refresh',exact:true}).click();
  await expect(command).toHaveCount(0);
  await expect(machines.getByRole('listitem')).toHaveCount(2);
  await expect(server).toContainText('Registered · Linux · Incus');
  await expect(server).toContainText('Online');
  await expect(page.getByRole('button',{name:'New workspace',exact:true})).toBeEnabled();
  await expect(page.locator('.stat-card').filter({hasText:'Online machines'}).locator('strong')).toHaveText('1');
  await server.locator('summary').filter({hasText:'Details'}).click();
  await expect(server).toContainText('host:metal-01');
  await expect(server.getByRole('button',{name:'Register server',exact:true})).toHaveCount(0);
  await server.getByRole('button',{name:'Revoke machine',exact:true}).click();
  await expect(server).toContainText('Registration required');
  await expect(machines.getByRole('listitem')).toHaveCount(2);
  await expect(server.getByRole('button',{name:'Register server',exact:true})).toBeVisible();
  await server.getByRole('button',{name:'Register server',exact:true}).click();
  await expect(page.getByLabel('Registration code',{exact:true})).toHaveValue(`${'5'.repeat(32)}.${'b'.repeat(64)}`);
  await expect(command).toHaveValue(/install-linux-node\.sh/);
  await page.setViewportSize({width:390,height:844});
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth)).toBe(true);
  await page.screenshot({path:'test-results/compute-linux-enrollment-mobile.png',fullPage:true});
});
