import { test, expect, type Page } from '@playwright/test';
import { createHmac, randomBytes } from 'node:crypto';
import { dashboardOrigin, fixtureOrigin } from './urls';
async function openMachines(page: Page) {
  const payload=Buffer.from(JSON.stringify({expires:Date.now()+3600000,nonce:randomBytes(24).toString('hex')})).toString('base64url');
  const signature=createHmac('sha256','fixture-session-secret-at-least-32-characters').update('fixture-dashboard-password').update('\0').update(payload).digest('base64url');
  await page.context().addCookies([{name:'enginebox_session',value:`${payload}.${signature}`,url:dashboardOrigin,httpOnly:true,sameSite:'Strict'}]);
  await page.goto('/');
  await page.getByRole('navigation',{name:'Control plane'}).getByRole('button',{name:'Compute',exact:true}).click();
}
test('copies the installer and raw code separately, renews the same identity, and moves a registered machine into the list',async ({page,request})=>{
  await request.post(`${fixtureOrigin}/__test/reset`);
  await openMachines(page);
  await page.getByRole('button',{name:'Add machine',exact:true}).click();
  await page.getByLabel('Machine name',{exact:true}).fill('Windows RTX');
  await expect(page.getByLabel('CPU cores',{exact:true})).toHaveCount(0);
  await page.getByRole('button',{name:'Create install command'}).click();
  const command=page.getByLabel('PowerShell install command');
  await expect(command).not.toHaveValue(/-Cpu|-MemoryGiB|-DiskGiB/);
  await expect(command).toHaveValue(/https:\/\/controller.fixture.example/);
  await expect(page.getByRole('region',{name:'Registered machines',exact:true}).getByRole('listitem', {name:'Machine Windows RTX',exact:true})).toHaveCount(0);
  await expect(page.getByRole('list',{name:'Pending registrations'})).not.toBeVisible();
  await page.context().grantPermissions(['clipboard-read','clipboard-write']);
  await page.getByRole('button',{name:'Copy install command',exact:true}).click();
  await expect(page.getByRole('button',{name:'Command copied',exact:true})).toBeVisible();
  expect(await page.evaluate(()=>navigator.clipboard.readText())).toContain('-Controller');
  await page.getByRole('button',{name:'Copy registration code',exact:true}).click();
  expect(await page.evaluate(()=>navigator.clipboard.readText())).toBe(`${'a'.repeat(32)}.${'b'.repeat(64)}`);
  await expect(page.getByRole('button',{name:'Code copied',exact:true})).toBeVisible();
  await page.locator('summary').filter({hasText:'Pending registrations'}).click();
  const pending=page.getByRole('list',{name:'Pending registrations'}).getByRole('listitem');
  await expect(pending).toContainText('a'.repeat(32));
  await pending.getByRole('button',{name:'Renew registration code'}).click();
  await expect(page.getByLabel('Registration code',{exact:true})).toHaveValue(`${'a'.repeat(32)}.${'c'.repeat(64)}`);
  await expect(command).toHaveValue(new RegExp('c'.repeat(64)));
  await expect(pending).toHaveCount(1);
  await page.getByRole('button',{name:'Copy registration code',exact:true}).click();
  expect(await page.evaluate(()=>navigator.clipboard.readText())).toBe(`${'a'.repeat(32)}.${'c'.repeat(64)}`);
  await page.screenshot({path:'test-results/contributors-enrollment-desktop.png',fullPage:true});
  await page.setViewportSize({width:390,height:844});
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth)).toBe(true);
  await page.screenshot({path:'test-results/contributors-enrollment-mobile.png',fullPage:true});
  await request.post(`${fixtureOrigin}/__test/contributor-online`);
  await page.getByRole('button',{name:'Refresh',exact:true}).click();
  await expect(command).toHaveCount(0);
  const row=page.getByRole('region',{name:'Registered machines',exact:true}).getByRole('listitem',{name:'Machine Windows RTX',exact:true});
  await expect(row).toContainText('Online');await expect(row).toContainText('Runtime ready');
  await expect(row).toContainText('2 CPU · 4 GiB memory');await expect(row).toContainText('20 GiB disk');
  await expect(row.getByRole('button',{name:'Renew registration code'})).toHaveCount(0);
  await row.locator('summary').filter({hasText:'Details'}).click();
  await row.getByRole('button',{name:'Revoke machine'}).click();
  await expect(row).toHaveCount(0);
  await page.locator('summary').filter({hasText:'Revoked machines and invitations'}).click();
  await expect(page.getByRole('list',{name:'Revoked machines and invitations'})).toContainText('Windows RTX');
});
