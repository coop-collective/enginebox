//! A run with a hosted repository: the guest writes a git config that sends
//! the token only to the repository's remote, the CLI process is pointed at
//! it, the token is scrubbed from output, and nothing is left behind.
#[cfg(unix)]
use enginebox_agents::{native, repository, security};
#[cfg(unix)]
use serde_json::json;

#[cfg(unix)]
const RUN: &str = "0123456789abcdef0123456789abcdef";
#[cfg(unix)]
const TOKEN: &str = "art_v1_0123456789abcdef0123456789abcdef01234567?expires=1760000000";
#[cfg(unix)]
const REMOTE: &str =
    "https://0123456789abcdef0123456789abcdef.artifacts.cloudflare.net/git/eb-alpha/game.git";

#[cfg(unix)]
fn fake_claude(home: &std::path::Path) {
    use std::os::unix::fs::PermissionsExt;
    security::safe_path(home, ".local/bin/claude", true).unwrap();
    let exe = home.join(".local/bin/claude");
    // Records what the CLI process sees: its variables, the included config,
    // and what git itself resolves for this remote and for another URL. It
    // also prints the token, which the helper must scrub.
    let script = "#!/bin/sh\nif [ \"$1\" = --version ]; then echo '2.1.310 (Claude Code)'; exit 0; fi\ncat >/dev/null\n\
        { echo \"remote=$ENGINEBOX_REPO_REMOTE\"; echo \"branch=$ENGINEBOX_REPO_DEFAULT_BRANCH\"; \
        echo \"count=$GIT_CONFIG_COUNT key=$GIT_CONFIG_KEY_0 value=$GIT_CONFIG_VALUE_0\"; \
        echo \"--- config\"; cat \"$GIT_CONFIG_VALUE_0\"; echo \"--- resolved\"; \
        git config --get-urlmatch http.extraHeader \"$ENGINEBOX_REPO_REMOTE/info/refs\"; \
        echo \"--- other\"; git config --get-urlmatch http.extraHeader https://example.com/other.git/info/refs; echo \"other_rc=$?\"; } >>\"$HOME/.seen\" 2>&1\n\
        echo \"leak: $(sed -n 's/.*Bearer //p' \"$GIT_CONFIG_VALUE_0\" | tr -d '\\\"')\"\n";
    std::fs::write(&exe, script).unwrap();
    std::fs::set_permissions(&exe, std::fs::Permissions::from_mode(0o700)).unwrap();
}

#[cfg(unix)]
#[test]
fn a_repository_run_gets_a_header_scoped_to_its_remote_and_leaves_nothing_behind() {
    if std::process::Command::new("git")
        .arg("--version")
        .output()
        .is_err()
    {
        eprintln!("git is not installed; skipping");
        return;
    }
    let t = tempfile::tempdir().unwrap();
    let root = t.path().canonicalize().unwrap();
    {
        use std::os::unix::fs::PermissionsExt;
        std::fs::set_permissions(&root, std::fs::Permissions::from_mode(0o700)).unwrap();
    }
    let home = root.join("home");
    let workspace = root.join("workspace");
    security::private_dir(&home).unwrap();
    security::private_dir(&workspace).unwrap();
    fake_claude(&home);
    let envelope = repository::Envelope {
        request: native::RunRequest::parse(json!({"provider":"claude","prompt":"push it"}))
            .unwrap(),
        profile: None,
        repository: repository::Access {
            remote: REMOTE.into(),
            default_branch: "main".into(),
            token: TOKEN.into(),
            auth: repository::Auth::Bearer,
        },
        checkout: None,
    };
    let out = native::execute_with_repository(&envelope, &home, &workspace, RUN).unwrap();
    assert_eq!(out.exit_code, 0, "{}", out.output);
    let secret = TOKEN.split_once("?expires=").unwrap().0;
    assert!(
        !out.output.contains(secret),
        "token must be scrubbed from output: {}",
        out.output
    );
    assert!(out.output.contains(native::REDACTED), "{}", out.output);
    let seen = std::fs::read_to_string(home.join(".seen")).unwrap();
    let config = repository::run_dir(&home, RUN).unwrap().join("gitconfig");
    assert!(seen.contains(&format!("remote={REMOTE}\n")), "{seen}");
    assert!(seen.contains("branch=main\n"), "{seen}");
    assert!(
        seen.contains(&format!(
            "count=1 key=include.path value={}\n",
            config.display()
        )),
        "{seen}"
    );
    let expected_config = format!(
        "# Generated by Engine Box for one run. Sends this repository's token only to its remote.\n[http \"{REMOTE}\"]\n\textraHeader = \"Authorization: Bearer {TOKEN}\"\n"
    );
    assert!(
        seen.contains(&format!("--- config\n{expected_config}--- resolved\n")),
        "{seen}"
    );
    assert!(
        seen.contains(&format!(
            "--- resolved\nAuthorization: Bearer {TOKEN}\n--- other\nother_rc=1\n"
        )),
        "git sends the header to this remote only: {seen}"
    );
    assert!(
        !repository::run_dir(&home, RUN).unwrap().exists(),
        "the run's git config is removed after the run"
    );
    // A caller cannot replace git's config injection in a repository run.
    let mut injected = envelope.clone();
    injected.request.env = [("GIT_CONFIG_COUNT".to_owned(), "0".to_owned())].into();
    assert!(native::execute_with_repository(&injected, &home, &workspace, RUN).is_err());
    // Without a run ID the helper refuses.
    assert!(native::execute_with_repository(&envelope, &home, &workspace, "bad").is_err());
    // An older helper's `run` refuses the envelope instead of running without it.
    assert!(native::RunRequest::parse(serde_json::to_value(&envelope).unwrap()).is_err());
}

#[cfg(unix)]
#[test]
fn each_repository_run_gets_a_fresh_checkout_at_a_stable_path() {
    use std::os::unix::fs::PermissionsExt;
    let t = tempfile::tempdir().unwrap();
    let root = t.path().canonicalize().unwrap();
    std::fs::set_permissions(&root, std::fs::Permissions::from_mode(0o700)).unwrap();
    let home = root.join("home");
    let workspace = root.join("workspace");
    security::private_dir(&home).unwrap();
    security::private_dir(&workspace).unwrap();
    security::safe_path(&home, ".local/bin/claude", true).unwrap();
    let exe = home.join(".local/bin/claude");
    // Like an agent that clones into ./repo: it fails if the directory exists.
    let script = "#!/bin/sh\nif [ \"$1\" = --version ]; then echo '2.1.310 (Claude Code)'; exit 0; fi\ncat >/dev/null\n\
        echo \"cwd=$(pwd) dir=$ENGINEBOX_RUN_DIR id=$ENGINEBOX_RUN_ID\"\n\
        mkdir repo || exit 3\n";
    std::fs::write(&exe, script).unwrap();
    std::fs::set_permissions(&exe, std::fs::Permissions::from_mode(0o700)).unwrap();
    let envelope = |checkout: Option<&str>| repository::Envelope {
        request: native::RunRequest::parse(json!({"provider":"claude","prompt":"work"})).unwrap(),
        profile: None,
        repository: repository::Access {
            remote: REMOTE.into(),
            default_branch: "main".into(),
            token: TOKEN.into(),
            auth: repository::Auth::Bearer,
        },
        checkout: checkout.map(str::to_owned),
    };
    let id = |c: char| c.to_string().repeat(32);
    let run = |c: char, e: repository::Envelope| {
        native::execute_with_repository(&e, &home, &workspace, &id(c)).unwrap()
    };
    let stable = workspace.join("game");
    // Two runs in a row use the same path (so harness state keyed by cwd
    // persists), and the second clone does not trip over the first's files.
    for c in ['a', 'b'] {
        let out = run(c, envelope(Some("game")));
        assert_eq!(out.exit_code, 0, "{}", out.output);
        assert!(
            out.output.contains(&format!(
                "cwd={} dir={} id={}",
                stable.display(),
                stable.display(),
                id(c)
            )),
            "{}",
            out.output
        );
        assert!(stable.join("repo").is_dir());
    }
    // Anything else left in the checkout is gone at the next run's start.
    std::fs::write(stable.join("leftover"), "x").unwrap();
    let out = run('c', envelope(Some("game")));
    assert_eq!(out.exit_code, 0, "{}", out.output);
    assert!(!stable.join("leftover").exists());
    // While another run (another provider) holds the stable checkout, a run
    // of the same repository works in a per-run directory, removed after.
    let held =
        security::Lease::acquire(&home, &format!("{}/game.lock", repository::CHECKOUT_LEASES))
            .unwrap();
    std::fs::write(stable.join("theirs"), "x").unwrap();
    let out = run('d', envelope(Some("game")));
    assert_eq!(out.exit_code, 0, "{}", out.output);
    let fallback = workspace.join(format!("game-{}", id('d')));
    assert!(
        out.output.contains(&format!("cwd={}", fallback.display())),
        "{}",
        out.output
    );
    assert!(!fallback.exists());
    assert!(
        stable.join("theirs").exists(),
        "the other run's checkout is untouched"
    );
    drop(held);
    // Without a checkout (older controllers) the run works in the workspace
    // as before and gets no ENGINEBOX_RUN_DIR.
    let out = run('e', envelope(None));
    assert_eq!(out.exit_code, 0, "{}", out.output);
    assert!(
        out.output
            .contains(&format!("cwd={} dir= id=\n", workspace.display())),
        "{}",
        out.output
    );
    // A caller cannot set ENGINEBOX_RUN_DIR, and a checkout name must be a
    // repository name.
    let mut injected = envelope(Some("game"));
    injected.request.env = [("ENGINEBOX_RUN_DIR".to_owned(), "/".to_owned())].into();
    assert!(native::execute_with_repository(&injected, &home, &workspace, &id('f')).is_err());
    for bad in ["../etc", "Game", "a/b", ""] {
        assert!(
            native::execute_with_repository(&envelope(Some(bad)), &home, &workspace, &id('f'))
                .is_err(),
            "{bad}"
        );
    }
}

mod service {
    use enginebox_agents::{
        AgentService,
        queue::{HostLoad, QueueLimits},
        repository, security,
        service::LaunchOptions,
    };
    use enginebox_core::{Fleet, Host};
    use serde_json::{Value, json};
    use std::{
        collections::BTreeMap,
        sync::{Arc, Mutex},
        time::{Duration, Instant},
    };

    fn service() -> (tempfile::TempDir, AgentService) {
        let t = tempfile::tempdir().unwrap();
        let root = t.path().canonicalize().unwrap();
        #[cfg(unix)]
        {
            use std::os::unix::fs::PermissionsExt;
            std::fs::set_permissions(&root, std::fs::Permissions::from_mode(0o700)).unwrap();
        }
        let home = root.join("agents/homes/claude");
        security::private_dir(&home).unwrap();
        security::write_json(
            &home,
            ".config/enginebox/controller-token.json",
            &json!({"kind":"setup_token","value":"controller-token-private","expires_at":null}),
        )
        .unwrap();
        let fleet = Fleet::from_hosts(
            vec![Host {
                id: "h1".into(),
                target: "h1.invalid".into(),
                max_agent_runs: Some(4),
                ..Default::default()
            }],
            &root,
        )
        .unwrap();
        let service =
            AgentService::with_limits(&root, fleet, BTreeMap::new(), QueueLimits::default())
                .unwrap();
        service.set_measure_hook(Arc::new(|_| {
            Ok(HostLoad {
                cpu_total: 64,
                reserve_cpu: 2,
                memory_available_bytes: 1 << 40,
                reserve_memory_bytes: 1 << 30,
            })
        }));
        service.start_scheduler();
        (t, service)
    }
    fn wait(service: &AgentService, id: &str) -> Value {
        let deadline = Instant::now() + Duration::from_secs(20);
        loop {
            let run = service.get_run("h1", "ebox-a", id).unwrap();
            if !["queued", "running"].contains(&run["status"].as_str().unwrap()) {
                return run;
            }
            assert!(Instant::now() < deadline, "run did not finish: {run}");
            std::thread::sleep(Duration::from_millis(20));
        }
    }
    fn launch(service: &AgentService, env: Value) -> anyhow::Result<String> {
        let (run, _) = service.launch_with(
            "h1",
            "ebox-a",
            json!({"provider":"claude","prompt":"x","env":env}),
            "owner",
            LaunchOptions {
                repository: Some("alpha/game".into()),
                ..Default::default()
            },
        )?;
        Ok(run["id"].as_str().unwrap().to_owned())
    }

    #[test]
    fn a_repository_run_fails_cleanly_when_no_token_can_be_minted() {
        let (_t, service) = service();
        let executed = Arc::new(Mutex::new(0));
        let count = executed.clone();
        service.set_run_executor(Arc::new(move |_| {
            *count.lock().unwrap() += 1;
            Ok(json!({"exit_code":0,"output":"","timed_out":false,"output_truncated":false}))
        }));
        // Caller env cannot carry git config injection.
        assert!(launch(&service, json!({"GIT_CONFIG_COUNT":"1"})).is_err());
        // No backend installed: the run fails at resolve, before any executor.
        let id = launch(&service, json!({})).unwrap();
        let run = wait(&service, &id);
        assert_eq!(run["status"], "failed");
        assert_eq!(
            run["failure"],
            json!({"stage":"resolve","reason":"repository_unavailable"})
        );
        assert_eq!(run["repository"], "alpha/game");
        assert!(run["error"].as_str().unwrap().contains("repository"));
        // The backend refuses: same, and the error detail stays out of the run.
        let ttls = Arc::new(Mutex::new(vec![]));
        let seen = ttls.clone();
        service.set_repository_hooks(
            Arc::new(move |reference, ttl| {
                seen.lock().unwrap().push((reference.to_owned(), ttl));
                anyhow::bail!("backend said no")
            }),
            Arc::new(|_, _| {}),
        );
        let id = launch(&service, json!({})).unwrap();
        let run = wait(&service, &id);
        assert_eq!(run["failure"]["reason"], "repository_unavailable");
        assert!(!run.to_string().contains("backend said no"));
        assert_eq!(
            ttls.lock().unwrap().clone(),
            [("alpha/game".to_owned(), repository::run_token_ttl(120))]
        );
        // A minted token with an unusable remote is refused too.
        service.set_repository_hooks(
            Arc::new(|_, _| {
                Ok(repository::Credential {
                    remote: "http://insecure.example/git/x.git".into(),
                    default_branch: "main".into(),
                    token: "art_v1_0123456789abcdef0123456789abcdef01234567".into(),
                    token_id: None,
                    expires_at: "2026-10-26T00:00:00Z".into(),
                    auth: repository::Auth::Bearer,
                })
            }),
            Arc::new(|_, _| {}),
        );
        let id = launch(&service, json!({})).unwrap();
        assert_eq!(
            wait(&service, &id)["failure"]["reason"],
            "repository_unavailable"
        );
        assert_eq!(*executed.lock().unwrap(), 0, "nothing ran without a token");
        let events = service.launch_events(&Default::default()).to_string();
        assert!(events.contains("repository_unavailable"));
    }
}
